#!/usr/bin/env python3
"""Render a service's coverage page from the emulator README and one data file.

The engine knows nothing about any one service: a `coverage/<service>.json` file
names the README row, the page it publishes, and what the console can do with each
operation. Adding a service is a data file, not more code here.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# The emulator's own operation list: a checkout beside the repo, or CI's pin.
EMULATOR = Path(os.environ.get("EP_EMULATOR_SRC") or ROOT.parent / "ministack-src")
README = EMULATOR / "README.md"
DATA = ROOT / "coverage"
BEGIN = "<!-- coverage:begin -->"
END = "<!-- coverage:end -->"
SEPARATOR = "| --- | --- | --- | --- |"
READ_PREFIXES = ("Get", "List", "Head", "Describe")
DASH = "\u2014"
NOT_CONSOLE = "not a console action"
# Sections of the ledger that are evidence, not the published claim.
SKIP = {"Console actions"}
TEST_FILE = re.compile(r"tests/[\w/]+\.\w+(?:\.\w+)*")
# The coverage section is generated too, so a new service never needs a hand edit.
# It is the map: one row per group, one page per group, one page per service, and
# no sidebar grows a line per service as the count climbs.
COVERAGE = ROOT / "site" / "docs" / "coverage"
INDEX = COVERAGE / "index.md"
INDEX_BEGIN = "<!-- coverage-index:begin -->"
INDEX_END = "<!-- coverage-index:end -->"
INDEX_LINK = "*Part of the [coverage map](../coverage/index.md).*\n\n"
GROUP_ORDER = ("Core", "Extended", "Infrastructure", "CloudFormation", "Other")
GROUP_SLUGS = {
    "Core": "core",
    "Extended": "extended",
    "Infrastructure": "infrastructure",
    "CloudFormation": "cloudformation",
    "Other": "other",
}


def is_read(operation: str) -> bool:
    return operation.startswith(READ_PREFIXES)


def load(service: str) -> dict:
    path = DATA / f"{service}.json"
    if not path.is_file():
        raise SystemExit(f"coverage: {path} is missing")
    return json.loads(path.read_text(encoding="utf-8"))


def console_actions(console_service: str) -> dict[str, str]:
    """The console catalogue's actions for one service; empty when it has none."""
    if not console_service:
        return {}
    sys.path.insert(0, str(ROOT / "control"))
    import console  # noqa: PLC0415 - read only here

    return {
        operation["id"]: operation["label"]
        for operation in console.CATALOGUE.get(console_service, {}).get("operations", [])
    }


def services() -> list[str]:
    return sorted(path.stem for path in DATA.glob("*.json"))


def upstream_operations(service: str) -> list[str]:
    """The operations the emulator README advertises for one service."""
    if not README.is_file():
        raise SystemExit(f"coverage: {README} is missing (ministack-src checkout)")
    marker = f"| **{service}** |"
    for line in README.read_text(encoding="utf-8").splitlines():
        if line.startswith(marker):
            cell = line.split("|")[2]
            # A structured row labels its sections; split on both separators, keep every entry.
            cell = re.sub(r"\*\*[^*]+\*\*:", " ", cell)
            return [part.strip() for part in re.split(r"[,;]", cell) if part.strip()]
    raise SystemExit(f"coverage: no `{marker}` row in the emulator README")


def operations_for(spec: dict) -> list[str]:
    """The row's operations minus any entry the ledger excludes as not an operation."""
    # A summary row (`List* (17 ops), Get*, ...`) names no operations; such a ledger lists them.
    if spec.get("operations"):
        return list(spec["operations"])
    excluded = set(spec.get("exclude") or [])
    return [op for op in upstream_operations(spec["service"]) if op not in excluded]


def render(spec: dict) -> str:
    service = spec["service"]
    operations = operations_for(spec)
    groups = spec.get("groups") or []
    gui = spec.get("gui") or {}
    covered = spec.get("covered") or {}
    blocked = spec.get("blocked") or {}
    not_console = spec.get("not_console") or {}
    pages = spec.get("pages") or {}
    action_operations = spec.get("action_operations") or {}
    actions = console_actions(spec.get("console_service", ""))
    tested_count = len([o for o in operations if o in covered])
    blocked_count = len([o for o in operations if o in blocked and o not in covered])
    untested_count = len(
        [o for o in operations if o not in covered and o not in blocked]
    )

    def evidence(name: str) -> str:
        if name in covered:
            return covered[name]
        if name in blocked:
            return f"blocked — {blocked[name]}"
        return DASH

    lines = [
        f"# {spec['title']}",
        "",
        f"Generated by `scripts/coverage.py` from the `| **{service}** |` row of the",
        "emulator's README and `control/console.py`. Do not edit by hand — re-run",
        "the script.",
        "",
        f"- Operations upstream advertises: **{len(operations)}**",
        f"- Console actions (`/api/exec`, the create page): **{len(actions)}**",
        f"- Operations with an emuplane test: **{tested_count}**",
        f"- Operations blocked on a dependant: **{blocked_count}**",
        f"- Operations shown in the console: **{len([o for o in operations if o in gui])}**",
        f"- Operations that are not console actions: "
        f"**{len([o for o in operations if o in not_console])}**",
        f"- GET operations (Get/List/Head/Describe) shown in the console: "
        f"**{len([o for o in operations if is_read(o) and o in gui])}** of "
        f"**{len([o for o in operations if is_read(o)])}**",
        f"- Operations with no emuplane test: "
        f"**{untested_count}**",
        "",
    ]
    if not groups and spec.get("group"):
        lines.append(
            f"- Group: **{spec['group']}** · operations: **{len(operations)}** · "
            + f"Console actions: **{len(actions)}**"
        )
        lines.append("")
    lines += spec.get("intro") or []

    grouped = {name for _, names in groups for name in names}
    ungrouped = [name for name in operations if name not in grouped]
    if ungrouped:
        lines += ["", "Ungrouped by this script: " + ", ".join(ungrouped)]

    for title, names in groups:
        listed = [name for name in names if name in operations]
        if not listed:
            continue
        lines += [
            "",
            f"## {title}",
            "",
            "| Operation | Console action | Shown in the console | Emuplane test |",
            "| --- | --- | --- | --- |",
        ]
        for name in listed:
            owned = [
                key for key in action_operations if name in action_operations[key]
            ]
            if name in pages:
                owned.append(pages[name])
            action = ", ".join(owned)
            test = evidence(name)
            shown = not_console.get(name) or gui.get(name, DASH)
            lines.append(f"| `{name}` | {action or DASH} | {shown} | {test} |")

    reads = [name for name in operations if is_read(name)]
    if reads and groups:
        lines += [
            "",
            "## GET operations",
            "",
            "Every read operation, and where the console shows it. A box left unticked",
            "is an operation the emulator answers and the console cannot display.",
            "",
        ]
        for name in reads:
            shown = gui.get(name)
            lines.append(
                f"- [{'x' if shown else ' '}] `{name}`"
                + (f" — {shown}" if shown else " — not shown")
            )

    if not groups:
        # A service with no hand-written groups: one table over the advertised row.
        lines += [
            "",
            "## Operations",
            "",
            "| Operation | Console action | Shown in the console | Emuplane test |",
            "| --- | --- | --- | --- |",
        ]
        for name in operations:
            owned = [key for key in action_operations if name in action_operations[key]]
            if name in pages:
                owned.append(pages[name])
            lines.append(
                f"| `{name}` | {', '.join(owned) or DASH} | "
                f"{not_console.get(name) or gui.get(name, 'not yet')} "
                f"| {evidence(name)} |"
            )

    if actions:
        lines += [
            "",
            "## Console actions",
            "",
            "| Action | Label |",
            "| --- | --- |",
        ]
        lines += [f"| `{key}` | {label} |" for key, label in sorted(actions.items())]

    lines.append("")
    return "\n".join(lines)


def published(text: str) -> str:
    """The part of the ledger the documentation page carries."""
    kept: list[str] = []
    section = ""
    for line in text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
            if section in SKIP:
                continue
            kept += ["", "##" + line[2:], ""]
        elif section in SKIP:
            continue
        elif line.startswith("- ") and "**" in line:
            kept.append(line)
        elif not line.strip():
            kept.append("")
        elif line.startswith("| `") or line.startswith("| Operation") or line == SEPARATOR:
            kept.append(line)
        elif line.startswith("- [x]") or line.startswith("- [ ]"):
            kept.append(line)
    return "\n".join(kept).strip()


def block(page: str) -> str:
    """The generated block of a documentation page."""
    if BEGIN not in page or END not in page:
        raise SystemExit("coverage: the page has no generated block markers")
    return page.partition(BEGIN)[2].partition(END)[0].strip()


def page_path(spec: dict) -> Path:
    return ROOT / spec["page"]


def missing_tests(spec: dict) -> list[str]:
    """Test paths the map names that are no longer on disk, so a rename cannot pass unnoticed."""
    named = set()
    for value in (spec.get("covered") or {}).values():
        named.update(TEST_FILE.findall(value))
    return sorted(path for path in named if not (ROOT / path).is_file())


def write(spec: dict) -> None:
    text = render(spec)
    ledger = ROOT / spec["ledger"] if spec.get("ledger") else None
    if ledger is not None:
        ledger.parent.mkdir(parents=True, exist_ok=True)
        ledger.write_text(text, encoding="utf-8")
    page = page_path(spec)
    current = page.read_text(encoding="utf-8")
    head, _, rest = current.partition(BEGIN)
    _, _, tail = rest.partition(END)
    page.write_text(
        head + BEGIN + "\n\n" + INDEX_LINK + published(text) + "\n\n" + END + tail,
        encoding="utf-8",
    )
    where = f"{ledger.relative_to(ROOT)} and " if ledger is not None else ""
    print(f"wrote {where}{page.relative_to(ROOT)}")


def index_rows() -> list[dict]:
    """One row per service: the counts the summary uses, plus the page and sidebar id."""
    rows = []
    for name in services():
        spec = load(name)
        operations = operations_for(spec)
        covered = set(spec.get("covered") or {})
        blocked = set(spec.get("blocked") or {})
        page = spec["page"].rsplit("reference/", 1)[-1]
        rows.append(
            {
                "service": spec["service"],
                "group": spec.get("group") or "Other",
                "operations": len(operations),
                "tested": len([op for op in operations if op in covered]),
                "blocked": len([op for op in operations if op in blocked and op not in covered]),
                "page": page,
            }
        )
    return rows


def group_order(rows: list[dict]) -> list[str]:
    """The emulator's own group order, then any label a ledger adds on its own."""
    known = [group for group in GROUP_ORDER if any(row["group"] == group for row in rows)]
    return known + sorted({row["group"] for row in rows} - set(known))


def group_rows(group: str) -> list[dict]:
    """One group's services, in the order the group page prints them."""
    return sorted(
        (row for row in index_rows() if row["group"] == group),
        key=lambda row: row["service"].lower(),
    )


def render_group(group: str) -> str:
    rows = group_rows(group)
    if not rows:
        return "No service in this group has a page yet."
    lines = [
        "| Service | Operations | Tested | Blocked | Page |",
        "| --- | ---: | ---: | ---: | --- |",
    ]
    for row in rows:
        label = row["page"].removesuffix(".md")
        lines.append(
            f"| {row['service']} | {row['operations']} | {row['tested']} | {row['blocked']} "
            f"| [{label}](../../reference/{row['page']}) |"
        )
    return "\n".join(lines)


def render_index() -> str:
    """The map: one row per group, with the counts its page repeats service by service."""
    rows = index_rows()
    totals = {key: sum(row[key] for row in rows) for key in ("operations", "tested", "blocked")}
    lines = [
        f"**{len(rows)} services** · {totals['operations']} operations · "
        f"{totals['tested']} tested · {totals['blocked']} blocked. Each page names the "
        "test behind every operation it counts.",
        "",
        "| Group | Services | Operations | Tested | Blocked |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for group in group_order(rows):
        members = group_rows(group)
        lines.append(
            f"| [{group}]({GROUP_SLUGS[group]}/index.md) | {len(members)} "
            f"| {sum(row['operations'] for row in members)} "
            f"| {sum(row['tested'] for row in members)} "
            f"| {sum(row['blocked'] for row in members)} |"
        )
    return "\n".join(lines).strip()


def group_page(group: str) -> Path:
    return COVERAGE / GROUP_SLUGS[group] / "index.md"


def group_pages() -> list[tuple[str, Path, str]]:
    """Every group's page, an empty one included, so the URL the map links to exists."""
    present = set(group_order(index_rows()))
    groups = [group for group in GROUP_ORDER if group != "Other" or "Other" in present]
    return [(group, group_page(group), render_group(group)) for group in groups]


def index_block(path: Path) -> str:
    """The generated block of a map page, which carries its own markers."""
    page = path.read_text(encoding="utf-8")
    if INDEX_BEGIN not in page or INDEX_END not in page:
        raise SystemExit(f"coverage: {path.relative_to(ROOT)} has no coverage-index markers")
    return page.partition(INDEX_BEGIN)[2].partition(INDEX_END)[0].strip()


def replace_block(path: Path, text: str) -> None:
    current = path.read_text(encoding="utf-8")
    if INDEX_BEGIN not in current or INDEX_END not in current:
        raise SystemExit(f"coverage: {path.relative_to(ROOT)} has no coverage-index markers")
    head, _, rest = current.partition(INDEX_BEGIN)
    _, _, tail = rest.partition(INDEX_END)
    path.write_text(
        head + INDEX_BEGIN + "\n\n" + text + "\n\n" + INDEX_END + tail, encoding="utf-8"
    )
    print(f"wrote {path.relative_to(ROOT)}")


def write_index() -> None:
    replace_block(INDEX, render_index())
    for _, path, text in group_pages():
        replace_block(path, text)


def check_index() -> bool:
    ok = True
    expected = [(INDEX, render_index())] + [(path, text) for _, path, text in group_pages()]
    for path, text in expected:
        if not path.is_file() or index_block(path) != text:
            print(f"{path.relative_to(ROOT)} is out of date: run scripts/coverage.py", file=sys.stderr)
            ok = False
    return ok



def write_summary() -> None:
    """One row per service: the honest answer to "how far has this grown?"."""
    rows = []
    for name in services():
        spec = load(name)
        operations = operations_for(spec)
        actions = console_actions(spec.get("console_service", ""))
        gui = spec.get("gui") or {}
        covered = spec.get("covered") or {}
        blocked = spec.get("blocked") or {}
        rows.append(
            {
                "service": spec["service"],
                "group": spec.get("group") or "",
                "operations": len(operations),
                "actions": len(actions),
                "shown": len([o for o in operations if o in gui]),
                "tested": len([o for o in operations if o in covered]),
                "blocked": len(
                    [o for o in operations if o in blocked and o not in covered]
                ),
                "page": spec["page"].rsplit("reference/", 1)[-1],
            }
        )
    rows.sort(key=lambda row: (row["group"], row["service"].lower()))

    lines = [
        "# Coverage across services",
        "",
        "Generated by `scripts/coverage.py` from `coverage/*.json` and the emulator",
        "README. One row per service: the operations the endpoint advertises, the",
        "actions the console drives, and how many are shown or tested.",
        "",
        "| Service | Group | Operations | Console actions | Shown | Tested | Blocked | Page |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['service']} | {row['group']} | {row['operations']} "
            f"| {row['actions']} | {row['shown']} | {row['tested']} "
            f"| {row['blocked']} | {row['page']} |"
        )
    totals = {
        key: sum(row[key] for row in rows)
        for key in ("operations", "actions", "shown", "tested", "blocked")
    }
    lines += [
        "",
        f"**{len(rows)} services** · {totals['operations']} operations · "
        f"{totals['actions']} console actions · {totals['shown']} shown · "
        f"{totals['tested']} tested · {totals['blocked']} blocked.",
        "",
    ]
    path = ROOT / "my-docs" / "COVERAGE.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def check(spec: dict) -> bool:
    stale = missing_tests(spec)
    if stale:
        print(
            "the map names tests that do not exist: " + ", ".join(stale),
            file=sys.stderr,
        )
        return False
    page = page_path(spec)
    current = block(page.read_text(encoding="utf-8")) if page.is_file() else ""
    if current != INDEX_LINK + published(render(spec)):
        print(
            f"{page.relative_to(ROOT)} is out of date: run scripts/coverage.py",
            file=sys.stderr,
        )
        return False
    return True


def main(argv: list[str]) -> int:
    wanted = [arg for arg in argv if not arg.startswith("-")]
    targets = wanted or services()
    if "--check" in argv:
        ok = True
        for name in targets:
            spec = load(name)
            if check(spec):
                print(f"{spec['title']} is current")
            else:
                ok = False
        ok = check_index() and ok
        return 0 if ok else 1
    for name in targets:
        write(load(name))
    write_summary()
    write_index()
    return 0
