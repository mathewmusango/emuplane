#!/usr/bin/env python3
"""Render a service's coverage page from the emulator README and one data file.

The engine knows nothing about any one service: a `coverage/<service>.json` file
names the README row, the page it publishes, and what the console can do with each
operation. Adding a service is a data file, not more code here.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# The emulator's own operation list: a checkout beside the repo, or CI's pin.
EMULATOR = Path(os.environ.get("EP_EMULATOR_SRC") or ROOT.parent / "ministack-src")
README = EMULATOR / "README.md"
DATA = ROOT / "coverage"
BEGIN = "<!-- coverage:begin -->"
END = "<!-- coverage:end -->"
SEPARATOR = "| --- | --- | --- | --- |"
READ_PREFIXES = ("Get", "List", "Head", "Describe")
DASH = "\u2014"
NOT_CONSOLE = "not a console action"
# Sections of the ledger that are evidence, not the published claim.
SKIP = {"Console actions"}
TEST_FILE = re.compile(r"tests/[\w/]+\.\w+(?:\.\w+)*")


def is_read(operation: str) -> bool:
    return operation.startswith(READ_PREFIXES)


def load(service: str) -> dict:
    path = DATA / f"{service}.json"
    if not path.is_file():
        raise SystemExit(f"coverage: {path} is missing")
    return json.loads(path.read_text(encoding="utf-8"))


def console_actions(console_service: str) -> dict[str, str]:
    """The console catalogue's actions for one service; empty when it has none."""
    if not console_service:
        return {}
    sys.path.insert(0, str(ROOT / "control"))
    import console  # noqa: PLC0415 - read only here

    return {
        operation["id"]: operation["label"]
        for operation in console.CATALOGUE.get(console_service, {}).get("operations", [])
    }


def services() -> list[str]:
    return sorted(path.stem for path in DATA.glob("*.json"))


def upstream_operations(service: str) -> list[str]:
    """The operations the emulator README advertises for one service."""
    if not README.is_file():
        raise SystemExit(f"coverage: {README} is missing (ministack-src checkout)")
    marker = f"| **{service}** |"
    for line in README.read_text(encoding="utf-8").splitlines():
        if line.startswith(marker):
            cell = line.split("|")[2]
            return [part.strip() for part in cell.split(",") if part.strip()]
    raise SystemExit(f"coverage: no `{marker}` row in the emulator README")


def render(spec: dict) -> str:
    service = spec["service"]
    operations = upstream_operations(service)
    groups = spec.get("groups") or []
    gui = spec.get("gui") or {}
    covered = spec.get("covered") or {}
    not_console = spec.get("not_console") or {}
    pages = spec.get("pages") or {}
    action_operations = spec.get("action_operations") or {}
    actions = console_actions(spec.get("console_service", ""))

    lines = [
        f"# {spec['title']}",
        "",
        f"Generated by `scripts/coverage.py` from the `| **{service}** |` row of the",
        "emulator's README and `control/console.py`. Do not edit by hand — re-run",
        "the script.",
        "",
        f"- Operations upstream advertises: **{len(operations)}**",
        f"- Console actions (`/api/exec`, the create page): **{len(actions)}**",
        f"- Operations with an emuplane test: **{len([o for o in operations if o in covered])}**",
        f"- Operations shown in the console: **{len([o for o in operations if o in gui])}**",
        f"- Operations that are not console actions: "
        f"**{len([o for o in operations if o in not_console])}**",
        f"- GET operations (Get/List/Head/Describe) shown in the console: "
        f"**{len([o for o in operations if is_read(o) and o in gui])}** of "
        f"**{len([o for o in operations if is_read(o)])}**",
        f"- Operations with no emuplane test: "
        f"**{len([o for o in operations if o not in covered])}**",
        "",
    ]
    if not groups and spec.get("group"):
        lines.append(
            f"- Group: **{spec['group']}** · operations: **{len(operations)}** · "
            + ("Console actions: **none yet**" if not actions else
               f"Console actions: **{len(actions)}**")
        )
        lines.append("")
    lines += spec.get("intro") or []

    grouped = {name for _, names in groups for name in names}
    ungrouped = [name for name in operations if name not in grouped]
    if ungrouped:
        lines += ["", "Ungrouped by this script: " + ", ".join(ungrouped)]

    for title, names in groups:
        listed = [name for name in names if name in operations]
        if not listed:
            continue
        lines += [
            "",
            f"## {title}",
            "",
            "| Operation | Console action | Shown in the console | Emuplane test |",
            "| --- | --- | --- | --- |",
        ]
        for name in listed:
            owned = [
                key for key in action_operations if name in action_operations[key]
            ]
            if name in pages:
                owned.append(pages[name])
            action = ", ".join(owned)
            test = covered.get(name, DASH)
            shown = not_console.get(name) or gui.get(name, DASH)
            lines.append(f"| `{name}` | {action or DASH} | {shown} | {test} |")

    reads = [name for name in operations if is_read(name)]
    if reads and groups:
        lines += [
            "",
            "## GET operations",
            "",
            "Every read operation, and where the console shows it. A box left unticked",
            "is an operation the emulator answers and the console cannot display.",
            "",
        ]
        for name in reads:
            shown = gui.get(name)
            lines.append(
                f"- [{'x' if shown else ' '}] `{name}`"
                + (f" — {shown}" if shown else " — not shown")
            )

    if not groups:
        # A service with no hand-written groups: one table over the advertised row.
        lines += [
            "",
            "## Operations",
            "",
            "| Operation | Console action | Shown in the console | Emuplane test |",
            "| --- | --- | --- | --- |",
        ]
        for name in operations:
            owned = [key for key in action_operations if name in action_operations[key]]
            if name in pages:
                owned.append(pages[name])
            lines.append(
                f"| `{name}` | {', '.join(owned) or DASH} | {gui.get(name, 'not yet')} "
                f"| {covered.get(name, DASH)} |"
            )

    if actions:
        lines += [
            "",
            "## Console actions",
            "",
            "| Action | Label |",
            "| --- | --- |",
        ]
        lines += [f"| `{key}` | {label} |" for key, label in sorted(actions.items())]

    lines.append("")
    return "\n".join(lines)


def published(text: str) -> str:
    """The part of the ledger the documentation page carries."""
    kept: list[str] = []
    section = ""
    for line in text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
            if section in SKIP:
                continue
            kept += ["", "##" + line[2:], ""]
        elif section in SKIP:
            continue
        elif line.startswith("- ") and "**" in line:
            kept.append(line)
        elif not line.strip():
            kept.append("")
        elif line.startswith("| `") or line.startswith("| Operation") or line == SEPARATOR:
            kept.append(line)
        elif line.startswith("- [x]") or line.startswith("- [ ]"):
            kept.append(line)
    return "\n".join(kept).strip()


def block(page: str) -> str:
    """The generated block of a documentation page."""
    if BEGIN not in page or END not in page:
        raise SystemExit("coverage: the page has no generated block markers")
    return page.partition(BEGIN)[2].partition(END)[0].strip()


def page_path(spec: dict) -> Path:
    return ROOT / spec["page"]


def missing_tests(spec: dict) -> list[str]:
    """Test paths the map names that are no longer on disk, so a rename cannot pass unnoticed."""
    named = set()
    for value in (spec.get("covered") or {}).values():
        named.update(TEST_FILE.findall(value))
    return sorted(path for path in named if not (ROOT / path).is_file())


def write(spec: dict) -> None:
    text = render(spec)
    ledger = ROOT / spec["ledger"] if spec.get("ledger") else None
    if ledger is not None:
        ledger.parent.mkdir(parents=True, exist_ok=True)
        ledger.write_text(text, encoding="utf-8")
    page = page_path(spec)
    current = page.read_text(encoding="utf-8")
    head, _, rest = current.partition(BEGIN)
    _, _, tail = rest.partition(END)
    page.write_text(
        head + BEGIN + "\n\n" + published(text) + "\n\n" + END + tail, encoding="utf-8"
    )
    where = f"{ledger.relative_to(ROOT)} and " if ledger is not None else ""
    print(f"wrote {where}{page.relative_to(ROOT)}")


def write_summary() -> None:
    """One row per service: the honest answer to "how far has this grown?"."""
    rows = []
    for name in services():
        spec = load(name)
        operations = upstream_operations(spec["service"])
        actions = console_actions(spec.get("console_service", ""))
        gui = spec.get("gui") or {}
        covered = spec.get("covered") or {}
        rows.append(
            {
                "service": spec["service"],
                "group": spec.get("group") or "",
                "operations": len(operations),
                "actions": len(actions),
                "shown": len([o for o in operations if o in gui]),
                "tested": len([o for o in operations if o in covered]),
                "page": spec["page"].rsplit("reference/", 1)[-1],
            }
        )
    rows.sort(key=lambda row: (row["group"], row["service"].lower()))

    lines = [
        "# Coverage across services",
        "",
        "Generated by `scripts/coverage.py` from `coverage/*.json` and the emulator",
        "README. One row per service: the operations the endpoint advertises, the",
        "actions the console drives, and how many are shown or tested.",
        "",
        "| Service | Group | Operations | Console actions | Shown | Tested | Page |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['service']} | {row['group']} | {row['operations']} "
            f"| {row['actions']} | {row['shown']} | {row['tested']} | {row['page']} |"
        )
    totals = {
        key: sum(row[key] for row in rows)
        for key in ("operations", "actions", "shown", "tested")
    }
    lines += [
        "",
        f"**{len(rows)} services** · {totals['operations']} operations · "
        f"{totals['actions']} console actions · {totals['shown']} shown · "
        f"{totals['tested']} tested.",
        "",
    ]
    path = ROOT / "my-docs" / "COVERAGE.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def check(spec: dict) -> bool:
    stale = missing_tests(spec)
    if stale:
        print(
            "the map names tests that do not exist: " + ", ".join(stale),
            file=sys.stderr,
        )
        return False
    page = page_path(spec)
    current = block(page.read_text(encoding="utf-8")) if page.is_file() else ""
    if current != published(render(spec)):
        print(
            f"{page.relative_to(ROOT)} is out of date: run scripts/coverage.py",
            file=sys.stderr,
        )
        return False
    return True


def main(argv: list[str]) -> int:
    wanted = [arg for arg in argv if not arg.startswith("-")]
    targets = wanted or services()
    if "--check" in argv:
        ok = True
        for name in targets:
            spec = load(name)
            if check(spec):
                print(f"{spec['title']} is current")
            else:
                ok = False
        return 0 if ok else 1
    for name in targets:
        write(load(name))
    write_summary()
    return 0
