#!/usr/bin/env python3
"""Generate the service TODO list from the upstream README.

The upstream "Supported Services" tables are the source of truth for what the
emulator can do; `control/console.py` is the source of truth for what our
console can do. This merges both into:

  docs/SERVICES.md   human summary + per-service operation list
  docs/services.json machine-readable copy for the UI/roadmap

Usage:
  python3 scripts/upstream_services.py                 # fetch upstream README
  python3 scripts/upstream_services.py --input FILE    # use a local copy
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = "https://raw.githubusercontent.com/ministackorg/ministack/main/README.md"
SECTION = re.compile(r"^###\s+(.+?)\s*$")
ROW = re.compile(r"^\|\s*\*\*(.+?)\*\*\s*\|\s*(.*?)\s*\|")

# Upstream display names that differ from the API/service name we sign with.
ALIASES = {
    "cloudwatch logs": "logs",
    "step functions": "stepfunctions",
    "secretsmanager": "secretsmanager",
    "ssm parameter store": "ssm",
    "kinesis": "kinesis",
}


def load_catalogue() -> dict:
    spec = importlib.util.spec_from_file_location(
        "console", ROOT / "control" / "console.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {
        service: [operation["id"] for operation in spec["operations"]]
        for service, spec in module.CATALOGUE.items()
    }


def parse(readme: str) -> dict[str, dict]:
    services: dict[str, dict] = {}
    group = ""
    inside = False
    for line in readme.splitlines():
        if line.startswith("## "):
            inside = "Supported Services" in line
            continue
        if not inside:
            continue
        heading = SECTION.match(line)
        if heading:
            group = heading.group(1).replace(" Services", "")
            continue
        row = ROW.match(line)
        if not row:
            continue
        name = re.sub(r"`|<br\s*/?>", "", row.group(1)).strip()
        operations = [
            item.strip()
            for item in re.sub(r"`", "", row.group(2)).split(",")
            if item.strip()
        ]
        services[name] = {"group": group or "Other", "operations": operations}
    return services


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", help="local README instead of fetching")
    args = parser.parse_args()

    if args.input:
        readme = Path(args.input).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(UPSTREAM, timeout=30) as response:
            readme = response.read().decode("utf-8")

    services = parse(readme)
    if not services:
        print("no services parsed — upstream layout changed?", file=sys.stderr)
        return 1

    catalogue = load_catalogue()
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)

    payload = {}
    rows = []
    for name, entry in services.items():
        cleaned = name.lower().replace(" (ec2 instance metadata)", "").strip()
        key = ALIASES.get(cleaned, cleaned)
        gui = catalogue.get(key, [])
        payload[name] = {**entry, "console_service": key if gui else "", "gui_actions": gui}
        rows.append((name, entry, gui))

    (docs / "services.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    total_ops = sum(len(entry["operations"]) for _, entry, _ in rows)
    covered = sum(1 for _, _, gui in rows if gui)
    lines = [
        "# Supported services and console coverage",
        "",
        "Generated by `scripts/upstream_services.py` from the upstream",
        "[supported services](https://github.com/ministackorg/ministack#supported-services)",
        "table and `control/console.py`. Do not edit by hand — re-run the script.",
        "",
        f"- Services upstream: **{len(rows)}**",
        f"- Operations upstream: **{total_ops}**",
        f"- Services with console actions: **{covered}**",
        "",
        "## Coverage",
        "",
        "| Service | Group | Operations | Console actions |",
        "| --- | --- | ---: | ---: |",
    ]
    for name, entry, gui in sorted(rows, key=lambda item: (item[1]["group"], item[0].lower())):
        label = f"[{name}](#{re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')})"
        lines.append(
            f"| {label} | {entry['group']} | {len(entry['operations'])} | {len(gui)} |"
        )

    lines += ["", "## TODO — no console actions yet", ""]
    todo = [
        (name, entry)
        for name, entry, gui in rows
        if not gui and entry["operations"]
    ]
    for name, entry in sorted(todo, key=lambda item: -len(item[1]["operations"])):
        lines.append(
            f"- [ ] **{name}** — {len(entry['operations'])} operations "
            f"({entry['group']})"
        )

    lines += ["", "## Operations per service", ""]
    for name, entry, gui in sorted(rows, key=lambda item: item[0].lower()):
        lines.append(f"### {name}")
        lines.append("")
        lines.append(f"Group: {entry['group']} · operations: {len(entry['operations'])}")
        if gui:
            lines.append(f"Console actions: {', '.join(gui)}")
        else:
            lines.append("Console actions: none yet")
        lines.append("")
        lines.append("<details><summary>Operations</summary>")
        lines.append("")
        lines.append(", ".join(entry["operations"]))
        lines.append("")
        lines.append("</details>")
        lines.append("")

    (docs / "SERVICES.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} services, {total_ops} operations -> docs/SERVICES.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
