const words = (name) =>
  name
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

export function serviceLabel(name) {
  if (!name) return ''
  if (name.length <= 3) return name.toUpperCase()
  return NAMES[name] || words(name)
}
